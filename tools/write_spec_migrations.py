#!/usr/bin/env python3
"""Write js/config/spec-id-migrations.js from every data/specs/*.json `legacy_ids` map.

Each subject's spec builder records earlier runtime skill ids whose meaning is now an
exact set of official leaves. This merges them so one subject's rebuild never drops
another subject's migrations.
"""
import json
from pathlib import Path


def write_migrations(repo):
    repo = Path(repo)
    merged = {}
    for path in sorted((repo / 'data/specs').glob('*.json')):
        legacy = json.loads(path.read_text()).get('legacy_ids') or {}
        for old, new in legacy.items():
            if old in merged and merged[old] != new:
                raise ValueError(f'Conflicting legacy id {old} in {path.name}')
            merged[old] = new
    target = repo / 'js/config/spec-id-migrations.js'
    target.write_text('// Generated by tools/write_spec_migrations.py from data/specs/*.json legacy_ids.\n'
                      '// Earlier runtime skill ids whose meaning is now an exact set of official leaves.\n'
                      '// Saved learned ticks expand once on load.\n'
                      'export const LEGACY_SPEC_IDS = Object.freeze(' + json.dumps(merged, indent=2) + ');\n')
    return len(merged)


if __name__ == '__main__':
    print(write_migrations(Path(__file__).resolve().parents[1]), 'legacy ids')
